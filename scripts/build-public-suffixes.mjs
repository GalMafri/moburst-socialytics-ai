// Writes supabase/functions/_shared/net/publicSuffixes.ts: the ICANN section
// of the Mozilla Public Suffix List (https://publicsuffix.org/), as the psl
// npm package ships it in node_modules/psl/data/rules.js, for the edge
// functions' registrable-domain rule (_shared/net/domains.ts). Run it again
// to take a newer list: node scripts/build-public-suffixes.mjs
//
// Kept: every rule of two or more labels, every wildcard and every exception,
// with internationalized labels in their ASCII (punycode) form, as hostnames
// reach the code. A one-label rule ("com") is left out: the list's default
// rule ("*") already treats every top-level label as a suffix. The private
// section (shared platforms such as myshopify.com) is left out on purpose:
// domains.ts keeps its own documented list of shared platforms.

import { readFileSync, writeFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';

const pkg = JSON.parse(readFileSync(new URL('../node_modules/psl/package.json', import.meta.url), 'utf8'));
const src = readFileSync(new URL('../node_modules/psl/data/rules.js', import.meta.url), 'utf8');
const all = [...src.matchAll(/^\s*"([^"]+)",?\s*$/gm)].map((m) => m[1]);
// The ICANN section ends with the last new gTLD; the private section starts after it.
const end = all.indexOf('zuerich');
if (end < 0 || all[end + 1] !== 'co.krd') throw new Error('The end of the ICANN section moved; check the list before regenerating.');
const ascii = (rule) => {
  const bang = rule.startsWith('!') ? '!' : '';
  const labels = rule.slice(bang.length).split('.').map((l) => (l === '*' ? '*' : domainToASCII(l) || l));
  return bang + labels.join('.');
};
const kept = [...new Set(all.slice(0, end + 1).map(ascii).filter((r) => r.startsWith('!') || r.includes('.')))].sort();
const lines = [];
for (let i = 0; i < kept.length; i += 12) lines.push(`  ${JSON.stringify(kept.slice(i, i + 12).join(' '))},`);
writeFileSync(new URL('../supabase/functions/_shared/net/publicSuffixes.ts', import.meta.url), `// GENERATED by scripts/build-public-suffixes.mjs: do not edit by hand.
//
// The ICANN section of the Mozilla Public Suffix List (https://publicsuffix.org/),
// as shipped in the ${pkg.name} npm package ${pkg.version}: every rule of two or more
// labels, every wildcard (*.) and exception (!), in ASCII form. ${kept.length} rules.

export const PUBLIC_SUFFIX_SOURCE = "Mozilla Public Suffix List, ICANN section, from ${pkg.name} ${pkg.version}";

export const PUBLIC_SUFFIX_RULES: readonly string[] = [
${lines.join('\n')}
].join(" ").split(" ");
`);
console.log(`Wrote ${kept.length} rules from ${pkg.name} ${pkg.version}.`);
