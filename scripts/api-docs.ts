/**
 * Builds every generated API file from the route table, in memory:
 *
 *   api/openapi.json           the OpenAPI document of the code as it is
 *   api/openapi.released.json  the last version consumers were told about;
 *                              it only moves forward through `npm run api:gen`
 *   docs/api/REFERENCE.md      the reference, rendered from the document
 *   docs/api/CHANGES.md        one dated entry per change, newest first
 *   supabase/functions/api/build-stamp.ts
 *                              a hash of the API function's source, served by
 *                              GET /v1/health, so the daily check can tell
 *                              whether production runs the code on main
 *
 * scripts/api-gen.ts writes them; the api-docs test compares them with the
 * committed files. A breaking change (see _shared/api/docs.ts) stops the
 * generator until it is listed in api/BREAKING.md with its date and what
 * replaces it.
 *
 * The same file in every Moburst tool; the tool-specific part is the config.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { diffOpenApi, renderChangeEntry, renderReference, stableJson, unacknowledged } from "../supabase/functions/_shared/api/docs";

export interface ApiDocsConfig {
  root: string;
  tool: string;
  /** The OpenAPI document of the current code. */
  openapi(): Record<string, unknown>;
  /** Folders whose source the API function is built from (repo-relative). */
  sourceDirs: string[];
  /** Further generated files (path -> content), for example the MCP tool manifest. */
  extraFiles?(): Record<string, string>;
  today?: string;
}

export interface Generated {
  files: Record<string, string>;
  /** Breaking changes not yet listed in api/BREAKING.md; the generator refuses to move the release forward. */
  blocked: string[];
}

const read = (root: string, path: string): string | null => (existsSync(join(root, path)) ? readFileSync(join(root, path), "utf8") : null);

export function sourceHash(root: string, dirs: string[]): string {
  const files: string[] = [];
  const walk = (dir: string) => {
    if (!existsSync(dir)) return;
    for (const name of readdirSync(dir).sort()) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.ts$/.test(name) && !/\.test\.ts$|\.fake\.ts$|build-stamp\.ts$/.test(name)) files.push(full);
    }
  };
  for (const d of dirs) walk(join(root, d));
  const h = createHash("sha256");
  for (const f of files) {
    h.update(relative(root, f));
    h.update(readFileSync(f));
  }
  return h.digest("hex").slice(0, 16);
}

export function generate(cfg: ApiDocsConfig): Generated {
  const today = cfg.today ?? new Date().toISOString().slice(0, 10);
  const doc = JSON.parse(stableJson(cfg.openapi()));
  const files: Record<string, string> = {};
  files["api/openapi.json"] = stableJson(doc);
  files["docs/api/REFERENCE.md"] = renderReference(doc, { tool: cfg.tool, regenerate: "npm run api:gen" });
  files["supabase/functions/api/build-stamp.ts"] =
    `// Generated by \`npm run api:gen\`: a hash of the API function's source, served by GET /v1/health.\n` +
    `// The daily production check compares it with main's to tell whether the deployed API is current.\n` +
    `export const BUILD_STAMP = ${JSON.stringify(sourceHash(cfg.root, cfg.sourceDirs))};\n`;
  Object.assign(files, cfg.extraFiles?.() ?? {});

  const releasedRaw = read(cfg.root, "api/openapi.released.json");
  const changes = read(cfg.root, "docs/api/CHANGES.md") ?? "# API changes\n\n<!-- Generated by `npm run api:gen`. Newest first. -->\n";
  if (!releasedRaw) {
    files["api/openapi.released.json"] = files["api/openapi.json"];
    files["docs/api/CHANGES.md"] = insertEntry(changes, `## ${today}\n\n- Baseline: the API as documented in REFERENCE.md.\n`);
    return { files, blocked: [] };
  }
  const released = JSON.parse(releasedRaw);
  const diff = diffOpenApi(released, doc);
  const blocked = unacknowledged(diff, read(cfg.root, "api/BREAKING.md") ?? "");
  if (blocked.length) {
    files["api/openapi.released.json"] = releasedRaw;
    files["docs/api/CHANGES.md"] = changes;
    return { files, blocked };
  }
  const entry = renderChangeEntry(diff, today);
  files["api/openapi.released.json"] = files["api/openapi.json"];
  files["docs/api/CHANGES.md"] = entry ? insertEntry(changes, entry) : changes;
  return { files, blocked: [] };
}

function insertEntry(changes: string, entry: string): string {
  const i = changes.indexOf("\n## ");
  return i < 0 ? `${changes.trimEnd()}\n\n${entry}` : `${changes.slice(0, i + 1)}${entry}\n${changes.slice(i + 1)}`;
}

/** Committed files that differ from what the generator would write now. */
export function stale(cfg: ApiDocsConfig, gen: Generated): string[] {
  return Object.entries(gen.files).filter(([path, content]) => read(cfg.root, path) !== content).map(([path]) => path);
}
